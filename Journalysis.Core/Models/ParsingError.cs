using System;

namespace Journalysis.Core.Models;

/// <summary>
/// Base type for a recoverable error encountered while parsing a source record.
/// </summary>
/// <typeparam name="TSource">
/// The reference type representing the source record whose parsing failed.
/// </typeparam>
/// <remarks>
/// A parsing error describes a parser diagnostic, not an exception recorded
/// inside the source file. The source may contain successfully parsed fields.
/// </remarks>
public abstract class ParsingError<TSource> where TSource : class
{
    /// <summary>
    /// Initializes a parsing error associated with a source record.
    /// </summary>
    /// <param name="source">The source record whose parsing encountered an error.</param>
    /// <param name="message">The diagnostic message generated by the parser.</param>
    /// <exception cref="ArgumentNullException">
    /// <paramref name="source"/> or <paramref name="message"/> is
    /// <see langword="null"/>.
    /// </exception>
    protected ParsingError(TSource source, string message)
    {
        ArgumentNullException.ThrowIfNull(source);
        ArgumentNullException.ThrowIfNull(message);

        Source = source;
        Message = message;
    }

    /// <summary>
    /// Gets the diagnostic message generated by the parser.
    /// </summary>
    public string Message { get; }

    /// <summary>
    /// Gets the source record whose parsing encountered an error.
    /// </summary>
    public TSource Source { get; }
}

/// <summary>
/// Represents a recoverable error encountered while parsing a journal record.
/// </summary>
/// <remarks>
/// The source record remains part of the parsed journal even when some
/// of its fields could not be extracted.
/// </remarks>
public sealed class JournalParsingError : ParsingError<JournalLine>
{
    /// <summary>
    /// Initializes a parsing error associated with a journal record.
    /// </summary>
    /// <param name="journalLine">The journal record whose parsing encountered an error.</param>
    /// <param name="message">The diagnostic message generated by the parser.</param>
    /// <exception cref="System.ArgumentNullException">
    /// <paramref name="journalLine"/> or <paramref name="message"/> is
    /// <see langword="null"/>.
    /// </exception>
    public JournalParsingError(JournalLine journalLine, string message)
        : base(journalLine, message)
    {
    }

    /// <summary>
    /// Gets the journal record whose parsing encountered an error.
    /// </summary>
    public JournalLine JournalLine => Source;
}